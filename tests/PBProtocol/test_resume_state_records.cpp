// Typed body sizes (tag byte included), pinned by the golden vectors below.
constexpr std::size_t kCompletedBodySize = 73;
constexpr std::size_t kWirehairHeaderBodySize = 45;
constexpr std::size_t kDirectRepeatHeaderBodySize = 17;

[[nodiscard]] constexpr std::byte Byte(const std::uint8_t value) noexcept
{
    return static_cast<std::byte>(value);
}

void WriteUint32LittleEndian(std::span<std::byte> target, const std::uint32_t value) noexcept
{
    for (std::size_t byteIndex = 0; byteIndex < sizeof(value); byteIndex++)
    {
        target[byteIndex] = Byte(
            static_cast<std::uint8_t>((value >> static_cast<unsigned int>(byteIndex * 8U)) & 0xFFU));
    }
}

void WriteUint64LittleEndian(std::span<std::byte> target, const std::uint64_t value) noexcept
{
    for (std::size_t byteIndex = 0; byteIndex < sizeof(value); byteIndex++)
    {
        target[byteIndex] = Byte(
            static_cast<std::uint8_t>((value >> static_cast<unsigned int>(byteIndex * 8U)) & 0xFFU));
    }
}

// Independent (test-local) body writers that hand-roll the documented layout.
// They exist so corruption and conflict fixtures can be constructed without
// relying on the module serializer; byte correctness is anchored by the
// golden literals further below, which were generated by an external
// reference implementation.
[[nodiscard]] std::vector<std::byte> BuildCompletedBody(
    const std::array<std::byte, 16>& sessionIdBytes,
    const std::uint64_t segmentOrdinal,
    const std::uint64_t rawOffset,
    const std::uint64_t rawSize,
    const std::array<std::byte, 32>& digestBytes)
{
    std::vector<std::byte> body(kCompletedBodySize);
    body[0] = Byte(1);
    for (std::size_t byteIndex = 0; byteIndex < 16U; byteIndex++)
    {
        body[1 + byteIndex] = sessionIdBytes[byteIndex];
    }
    WriteUint64LittleEndian(std::span<std::byte>(body).subspan(17), segmentOrdinal);
    WriteUint64LittleEndian(std::span<std::byte>(body).subspan(25), rawOffset);
    WriteUint64LittleEndian(std::span<std::byte>(body).subspan(33), rawSize);
    for (std::size_t byteIndex = 0; byteIndex < 32U; byteIndex++)
    {
        body[41 + byteIndex] = digestBytes[byteIndex];
    }
    return body;
}

[[nodiscard]] std::vector<std::byte> BuildWirehairBody(
    const std::uint64_t segmentOrdinal,
    const std::array<std::byte, 32>& profileBytes,
    const std::vector<std::pair<std::uint32_t, std::vector<std::byte>>>& entries)
{
    std::vector<std::byte> body(kWirehairHeaderBodySize);
    body[0] = Byte(2);
    WriteUint64LittleEndian(std::span<std::byte>(body).subspan(1), segmentOrdinal);
    for (std::size_t byteIndex = 0; byteIndex < 32U; byteIndex++)
    {
        body[9 + byteIndex] = profileBytes[byteIndex];
    }
    WriteUint32LittleEndian(std::span<std::byte>(body).subspan(41), static_cast<std::uint32_t>(entries.size()));
    for (const auto& [outerBlockId, payload] : entries)
    {
        const std::size_t entryStart = body.size();
        body.resize(entryStart + 8);
        WriteUint32LittleEndian(std::span<std::byte>(body).subspan(entryStart), outerBlockId);
        WriteUint32LittleEndian(
            std::span<std::byte>(body).subspan(entryStart + 4U),
            static_cast<std::uint32_t>(payload.size()));
        body.insert(body.end(), payload.begin(), payload.end());
    }
    return body;
}

[[nodiscard]] std::vector<std::byte> BuildDirectRepeatBody(
    const std::uint64_t segmentOrdinal,
    const std::uint32_t directBlockCount,
    const std::vector<std::tuple<std::uint32_t, std::uint32_t, std::vector<std::byte>>>& entries)
{
    std::vector<std::byte> body(kDirectRepeatHeaderBodySize);
    body[0] = Byte(3);
    WriteUint64LittleEndian(std::span<std::byte>(body).subspan(1), segmentOrdinal);
    WriteUint32LittleEndian(std::span<std::byte>(body).subspan(9), directBlockCount);
    WriteUint32LittleEndian(std::span<std::byte>(body).subspan(13), static_cast<std::uint32_t>(entries.size()));
    for (const auto& [blockOrdinal, realPayloadBytes, paddedPayload] : entries)
    {
        const std::size_t entryStart = body.size();
        body.resize(entryStart + 12);
        WriteUint32LittleEndian(std::span<std::byte>(body).subspan(entryStart), blockOrdinal);
        WriteUint32LittleEndian(
            std::span<std::byte>(body).subspan(entryStart + 4U), realPayloadBytes);
        WriteUint32LittleEndian(
            std::span<std::byte>(body).subspan(entryStart + 8U),
            static_cast<std::uint32_t>(paddedPayload.size()));
        body.insert(body.end(), paddedPayload.begin(), paddedPayload.end());
    }
    return body;
}

[[nodiscard]] std::vector<std::byte> WrapEnvelope(
    const std::span<const std::byte> payload)
{
    std::vector<std::byte> record(kResumeRecordEnvelopeBytes + payload.size());
    REQUIRE(SerializeResumeRecord(payload, std::span<std::byte>(record)));
    return record;
}

