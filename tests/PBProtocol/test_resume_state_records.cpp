// Deterministic xorshift64 generator for the seeded round-trip matrix.
[[nodiscard]] std::uint64_t NextXorShift(std::uint64_t& state) noexcept
{
    state ^= state << 13U;
    state ^= state >> 7U;
    state ^= state << 17U;
    return state;
}
